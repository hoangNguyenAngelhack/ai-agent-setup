import { ADAPTER_IDS, type ValidationReport } from '../registry';

export const SUMMARY_BEGIN = '<!-- catalog-summary:begin (generated by `npm run docs:summary`; do not edit) -->';
export const SUMMARY_END = '<!-- catalog-summary:end -->';

type Entry = ValidationReport['entries'][number];

function countWhere(entries: readonly Entry[], predicate: (entry: Entry) => boolean): number {
  return entries.filter(predicate).length;
}

function agentsRow(entries: readonly Entry[]): string {
  const canonical = countWhere(entries, (entry) => entry.kind === 'Agent' && entry.aliasOf === null);
  const aliases = countWhere(entries, (entry) => entry.kind === 'Agent' && entry.aliasOf !== null);
  return `${canonical} canonical + ${aliases} V1 aliases`;
}

function rulesRow(entries: readonly Entry[]): string {
  const rules = entries.flatMap((entry) => (entry.kind === 'Rule' ? [entry] : []));
  const scoped = (key: 'always' | 'paths' | 'capabilities') => rules.filter((rule) => key in rule.scope).length;
  return `${rules.length} (${scoped('always')} always-scoped, ${scoped('paths')} path-scoped, ${scoped('capabilities')} capability-scoped)`;
}

function toolsRow(entries: readonly Entry[]): string {
  const mcp = countWhere(entries, (entry) => entry.kind === 'Tool' && entry.type === 'mcp');
  const other = countWhere(entries, (entry) => entry.kind === 'Tool' && entry.type !== 'mcp');
  return `${mcp} MCP servers (opt-in) + ${other} other`;
}

/**
 * Markdown table of catalog counts, generated so README numbers never drift from the catalog
 * (TD-17, FR-17). Counts only: no claims about effect.
 */
export function catalogSummary(report: ValidationReport): string {
  const { entries, policies } = report;
  const ofKind = (kind: Entry['kind']) => String(countWhere(entries, (entry) => entry.kind === kind));
  const policyRules = policies.reduce((sum, policy) => sum + policy.rules.length, 0);
  const rows: Array<[string, string]> = [
    ['Domains', ofKind('Domain')],
    ['Capabilities', ofKind('Capability')],
    ['Agents', agentsRow(entries)],
    ['Skills', ofKind('Skill')],
    ['Rules', rulesRow(entries)],
    ['Workflows', ofKind('Workflow')],
    ['Profiles', ofKind('Profile')],
    ['Tools', toolsRow(entries)],
    ['Policies', `${policies.length} (${policyRules} rules)`],
    ['Adapters', ADAPTER_IDS.join(', ')],
  ];
  return [SUMMARY_BEGIN, '| Catalog | Count |', '|---|---|', ...rows.map(([name, value]) => `| ${name} | ${value} |`), SUMMARY_END].join('\n');
}

/** Replaces the generated block in a document; throws when the markers are missing. */
export function replaceSummaryBlock(document: string, summary: string): string {
  const start = document.indexOf(SUMMARY_BEGIN);
  const end = document.indexOf(SUMMARY_END);
  if (start === -1 || end === -1) throw new Error('catalog-summary markers not found');
  return document.slice(0, start) + summary + document.slice(end + SUMMARY_END.length);
}
