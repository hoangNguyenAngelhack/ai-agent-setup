/**
 * Shared value types exchanged between Core modules (docs/v2/05 §5). Types only: behaviour lives
 * in the module that owns each type. JSON Schemas for the persisted contracts are in
 * `catalog/schemas/` (gate-result, manifest).
 */

export type GateStatus = 'PASS' | 'FAIL' | 'NOT_VERIFIED';

export type GateCategory =
  | 'build'
  | 'unit'
  | 'integration'
  | 'e2e'
  | 'security'
  | 'performance'
  | 'accessibility'
  | 'documentation'
  | 'deployment-readiness';

export interface GateEvidence {
  type: 'command' | 'artifact' | 'review-note';
  command?: string;
  exitCode?: number;
  startedAt?: string;
  durationMs?: number;
  artifact?: string;
  summary?: Record<string, unknown>;
}

/** Contract: `urn:ai-agent-setup:contracts:v1:gate-result` (ADR-008). */
export interface GateResult {
  gate: string;
  category: GateCategory;
  status: GateStatus;
  measured: boolean;
  evidence: GateEvidence[];
  reason: string | null;
}

/**
 * Output of Project Detection (W2.0-06): the technology stack only. Every list is sorted and
 * de-duplicated; an empty list means "not detected", never "assumed". Existing AI host
 * configuration is detected by adapters (HostConfigDetection) to keep the Core host-neutral.
 */
export interface ProjectProfile {
  root: string;
  languages: string[];
  frameworks: string[];
  packageManagers: string[];
  buildTools: string[];
  testRunners: string[];
  ci: string[];
  /** Coarse traits matched against capability `requiredContext.projectSignals`. */
  signals: string[];
  /** Relative paths of detected sub-projects (apps/*, packages/*, services/*, libs/*). */
  workspaces: string[];
}

/** What an adapter found of its host's configuration in a repository. */
export interface HostConfigDetection {
  adapter: string;
  present: boolean;
  /** Relative paths that exist, sorted. */
  artifacts: string[];
  /** True when the files match the layout generated by create-ai-agent-setup V1 (docs/v2/07 §4.1). */
  v1Fingerprint: boolean;
}

/** A figure is either measured from an executed source or estimated; reports never mix them. */
export interface Quantity {
  value: number;
  unit: string;
  label: 'measured' | 'estimated';
}
