import { slugOf, type GenerationContext } from './generation-context';

/**
 * Managed, always-loaded instruction preamble (T0, docs/v2/05 §8): workflows, agents, required
 * gates with evidence rules, and the safety rules enforced by the policy hook.
 */
export function instructionPreamble(context: GenerationContext, invokePrefix: string, workflowName: (id: string) => string): string {
  const { profile, toolkitVersion, policies } = context.input;
  const workflows = context.list('Workflow').map((workflow) => `- \`${invokePrefix}${workflowName(workflow.id)}\`: ${workflow.description}`);
  const agents = context
    .list('Agent')
    .filter((agent) => context.body(agent) !== null)
    .map((agent) => `- \`${slugOf(agent)}\`: ${agent.aliasOf ? agent.purpose : agent.description}`);
  const safety = policies.flatMap((policy) =>
    policy.rules.filter((rule) => rule.effect !== 'allow').map((rule) => `- ${rule.effect === 'deny' ? 'Blocked' : 'Needs approval'}: ${rule.description}`),
  );

  return [
    '# AI engineering configuration',
    '',
    `Generated by create-ai-agent-setup ${toolkitVersion} from profile \`${profile.id}\` (${profile.name}).`,
    'Content between the ai-agent-setup markers is replaced on update; keep your own notes outside them.',
    '',
    '## Workflows',
    '',
    ...workflows,
    '',
    '## Agents',
    '',
    ...agents,
    '',
    '## Quality gates',
    '',
    `Required by this profile: ${profile.gates.map((gate) => `\`${gate}\``).join(', ') || 'none'}.`,
    'Report every gate as PASS, FAIL or NOT_VERIFIED. PASS requires a command you actually ran and its exit code;',
    'if a gate cannot run, report NOT_VERIFIED with the reason. Keep measured values separate from estimates.',
    '',
    '## Safety',
    '',
    'A policy hook checks these actions; they need explicit approval or are blocked:',
    '',
    ...safety,
  ].join('\n');
}
